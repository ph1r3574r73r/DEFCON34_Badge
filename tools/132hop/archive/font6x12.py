FONT_BYTES = b"".join(_RAW)
assert len(FONT_BYTES) == 16 * FONT_H


def font_words() -> list[int]:
    out = []
    for i in range(0, len(FONT_BYTES), 4):
        out.append(int.from_bytes(FONT_BYTES[i : i + 4], "little"))
    return out


def font_asm() -> str:
    lines = ["font:"]
    for w in font_words():
        lines.append(f"    .word 0x{w:08x}")
    return "\n".join(lines) + "\n"
