"""6×12 hex font. Glyph index == nibble value. bit0 = leftmost pixel."""

from __future__ import annotations

FONT_W = 6
FONT_H = 12


def _glyph(*rows: str) -> bytes:
    out = []
    for row in rows:
        if len(row) != FONT_W:
            raise ValueError(row)
        b = 0
        for i, ch in enumerate(row):
            if ch not in " .":
                b |= 1 << i
        out.append(b)
    if len(out) != FONT_H:
        raise ValueError(f"need {FONT_H} rows, got {len(out)}")
    return bytes(out)


